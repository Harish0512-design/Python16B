# collections module in python:
###################################
# 1. Python's normal built-in data structures like 'list', 'tuple', 'set', 'dict' are powerful - but not always optimal for all use cases.
# 2. For example:
# - You want a dictionary with default values - but normal dict throws keyError.
# - You want to count items efficiently
# - You want a queue(FIFO) and stack(LIFO) that performs well.
# - You want a dictionary that remembers insertion order (before python 3.7 this is relevant)

# So, collections module is introduced to provide specilized container data types that extend or optimize the basic ones.
# Collections module provides high-performance container datatypes beyond the built-ins.

# It provides:
#  1. Fast, memory-efficient alternatives.
#  2. Readable and concise code.
#  3. Solutions to common data manipulation problems.

# Different concepts/classes in collections module:
# 1. namedtuple()
# 2. Counter()
# 3. deque()
# 4. OrderedDict()
# 5. defaultdict()
# 6. ChainMap()
# 7. UserDict
# 8. UserList
# 9. UserString

